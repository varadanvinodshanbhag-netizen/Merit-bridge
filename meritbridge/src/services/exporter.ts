// ─────────────────────────────────────────────────────────────────────────────
// MeritBridge Data Exporter — Strictly matching PRD Section 10.2
// Exports filtered lists to Excel (.xlsx) and CSV with filter metadata.
// ─────────────────────────────────────────────────────────────────────────────

import * as XLSX from "xlsx";
import { format } from "date-fns";

export interface ExportOptions {
  filename: string;
  sheetName?: string;
  data: Record<string, unknown>[];
  filtersApplied?: Record<string, string | number | boolean | null | undefined>;
  staffName?: string;
}

export function exportToExcel(options: ExportOptions): void {
  const { filename, sheetName = "Data", data, filtersApplied, staffName = "Placement Staff" } = options;
  const now = new Date();
  const timestampStr = format(now, "yyyy-MM-dd_HHmm");
  const fullFilename = `${filename}_${timestampStr}.xlsx`;

  // 1. Data Worksheet
  const dataWs = XLSX.utils.json_to_sheet(data);

  // Auto-size columns
  if (data.length > 0) {
    const colWidths = Object.keys(data[0]).map((key) => {
      let maxLen = key.length;
      for (const row of data) {
        const val = row[key];
        const strVal = val !== undefined && val !== null ? String(val) : "";
        if (strVal.length > maxLen) maxLen = Math.min(strVal.length, 50);
      }
      return { wch: Math.max(maxLen + 3, 12) };
    });
    dataWs["!cols"] = colWidths;
  }

  // 2. Metadata / Filters Applied Worksheet (PRD Section 10.2)
  const metaRows: { Property: string; Value: string }[] = [
    { Property: "Report Name", Value: filename },
    { Property: "Generated On", Value: format(now, "dd/MM/yyyy HH:mm:ss") },
    { Property: "Generated By", Value: staffName },
    { Property: "Total Records Exported", Value: String(data.length) },
  ];

  if (filtersApplied) {
    for (const [k, v] of Object.entries(filtersApplied)) {
      if (v !== undefined && v !== null && v !== "") {
        metaRows.push({ Property: `Filter: ${k}`, Value: String(v) });
      }
    }
  }

  const metaWs = XLSX.utils.json_to_sheet(metaRows);
  metaWs["!cols"] = [{ wch: 25 }, { wch: 45 }];

  // 3. Create Workbook
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, dataWs, sheetName);
  XLSX.utils.book_append_sheet(wb, metaWs, "Export_Info");

  // 4. Trigger download
  XLSX.writeFile(wb, fullFilename);
}

export function exportToCsv(options: ExportOptions): void {
  const { filename, data } = options;
  const timestampStr = format(new Date(), "yyyy-MM-dd_HHmm");
  const fullFilename = `${filename}_${timestampStr}.csv`;

  const ws = XLSX.utils.json_to_sheet(data);
  const csvOutput = XLSX.utils.sheet_to_csv(ws);

  const blob = new Blob([csvOutput], { type: "text/csv;charset=utf-8;" });
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.setAttribute("download", fullFilename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
